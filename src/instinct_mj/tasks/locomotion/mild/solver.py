"""Batched discrete contact mechanics, independent of the environment API."""

from __future__ import annotations

import math

import torch


def granular_law(depth, velocity_z, area_weights, material, reference_area):
    """Positive-depth growing-cone law with resolution-independent quadrature.

    h = h0 - depth, z points up. Positive coefficients describe passive added
    mass. Conical area is the positive lateral-area magnitude. The reference
    cone is integrated once and weighted by actual cell area / reference area.
    Return quasi-static force, dF/dd, added mass, and entry drag (all per cell).
    """
    radius = math.sqrt(reference_area / math.pi)
    slope = material["recruitment"] / torch.tan(material["alpha"])
    cone_radius = radius + slope * depth
    integral = math.pi * (radius**2 * depth + radius * slope * depth**2 + slope**2 * depth**3 / 3)
    flat_area = math.pi * cone_radius**2
    lateral_integral = (integral - reference_area * depth) / torch.cos(material["alpha"])
    lateral_area = (flat_area - reference_area) / torch.cos(material["alpha"])
    stiffness = material["penetration_stiffness"] / reference_area
    quasi = area_weights * (stiffness * integral + material["conical_stress"] * lateral_integral)
    derivative = area_weights * (stiffness * flat_area + material["conical_stress"] * lateral_area)
    density_scale = material["mass_scale"] * material["volume_fraction"] * material["density"] * material["recruitment"]
    mass = area_weights * density_scale * integral
    # Recruitment only during downward intrusion; unloading must not create
    # an artificial downward suction force or negative accumulated mass.
    drag = area_weights * material["drag_scale"] * density_scale * flat_area * velocity_z.clamp(max=0).square()
    return quasi, derivative, mass, drag


def project_friction(impulse, normal_impulse, friction):
    radius = (normal_impulse * friction).clamp(min=0)
    return impulse * (radius / impulse.norm(dim=-1).clamp(min=1.0e-12)).clamp(max=1).unsqueeze(-1)


def solve_contact(mass_matrix, jacobian, qvel, free_force, bias_acceleration,
                  force_base, effective_mass, drift_force, friction, active,
                  previous_impulse, dt, friction_iterations, coupling_iterations):
    """Implicit normal added mass + maximum-dissipation tangential impulses.

    All point velocities are generated by the SAME generalized velocity. This
    enforces rigid-foot continuity exactly, including cross-foot inertial
    coupling, rather than subtracting a scalar continuity norm from a vector.
    Normal law: Fz = max(Fbase - meff * (Jz*qdd + bias_z), 0).
    meff includes dt^2*dF/dd (linearized backward-Euler spring stabilization).
    An active-set outer iteration handles unilateral normal force and its
    coupling to the Coulomb disks. The inner projected-gradient solve is
    matrix-free in contact space; only nv x nv matrices are factorized.
    """
    jz = jacobian[:, :, 2]
    jt = jacobian[:, :, :2].flatten(1, 2)
    torque_drift = torch.einsum("bcin,bci->bn", jacobian[:, :, :2], drift_force)
    rhs_free = free_force + torque_drift
    tangent = previous_impulse.clone() * active.unsqueeze(-1)
    normal_active = active
    residual = torch.zeros_like(force_base[:, 0])
    for _ in range(coupling_iterations):
        meff = effective_mass * normal_active
        base = (force_base - meff * bias_acceleration[:, :, 2]) * normal_active
        augmented = mass_matrix + jz.transpose(1, 2) @ (meff.unsqueeze(-1) * jz)
        # ex variants avoid a per-substep GPU/CPU error-check synchronization
        # and can be captured. Nonfinite state is checked at policy boundaries.
        factor = torch.linalg.cholesky_ex(augmented, check_errors=False)[0]
        rhs = rhs_free + torch.einsum("bcn,bc->bn", jz, base)
        white_all = torch.linalg.solve_triangular(
            factor, torch.cat((rhs.unsqueeze(-1), jt.transpose(1, 2)), dim=-1), upper=False
        )
        solution = torch.linalg.solve_triangular(factor.transpose(1, 2), white_all, upper=True)
        acceleration0 = solution[:, :, 0]
        response = solution[:, :, 1:]
        # A Gershgorin bound on the small whitened Gram matrix bounds the
        # Lipschitz constant of Jt M_eff^-1 Jt^T without forming that matrix.
        white = white_all[:, :, 1:]
        gram = white @ white.transpose(1, 2)
        step = 0.95 / gram.abs().sum(-1).amax(-1).clamp(min=1.0e-6)
        velocity0 = torch.einsum("bkn,bn->bk", jt, qvel + dt * acceleration0)
        velocity0 = velocity0 + dt * bias_acceleration[:, :, :2].flatten(1)
        for _ in range(friction_iterations):
            dq = (response @ tangent.flatten(1).unsqueeze(-1)).squeeze(-1)
            acceleration = acceleration0 + dq / dt
            normal = (base - meff * torch.einsum("bcn,bn->bc", jz, acceleration)).clamp(min=0)
            velocity = velocity0 + (jt @ dq.unsqueeze(-1)).squeeze(-1)
            proposed = tangent - step[:, None, None] * velocity.reshape_as(tangent)
            next_tangent = project_friction(proposed, normal * dt, friction) * active.unsqueeze(-1)
            residual = (next_tangent - tangent).norm(dim=-1).amax(-1)
            tangent = next_tangent
        dq = (response @ tangent.flatten(1).unsqueeze(-1)).squeeze(-1)
        acceleration = acceleration0 + dq / dt
        raw_normal = force_base - effective_mass * (
            torch.einsum("bcn,bn->bc", jz, acceleration) + bias_acceleration[:, :, 2]
        )
        normal_active = active & (raw_normal > 0)
    normal = raw_normal.clamp(min=0) * active
    tangent = project_friction(tangent, normal * dt, friction) * active.unsqueeze(-1)
    forces = torch.cat((tangent / dt + drift_force, normal.unsqueeze(-1)), dim=-1)
    # Report actual constitutive residual after projection, not just iterate delta.
    rhs_actual = free_force + torch.einsum("bcin,bci->bn", jacobian, forces)
    mass_factor = torch.linalg.cholesky_ex(mass_matrix, check_errors=False)[0]
    actual_white = torch.linalg.solve_triangular(mass_factor, rhs_actual.unsqueeze(-1), upper=False)
    actual_acc = torch.linalg.solve_triangular(mass_factor.transpose(1, 2), actual_white, upper=True).squeeze(-1)
    expected = (force_base - effective_mass * (
        torch.einsum("bcn,bn->bc", jz, actual_acc) + bias_acceleration[:, :, 2]
    )).clamp(min=0) * active
    normal_residual = (normal - expected).abs().amax(-1)
    return forces, tangent, residual, normal_residual
